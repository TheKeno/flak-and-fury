// The hangar's plane cards (data/plane-cards.json): each plane's character as the hangar shows it when a
// player picks a plane (fighter design pass, 2026-11-12: no extra HUD in flight, the character is shown
// here instead). Numbers from the plane sheet (src/balance/sheet.js: the real flight model), so they match
// how the plane flies; run this after plane numbers change (tools/fit-planes.mjs, the tuner's Apply).
// tests/plane-cards.test.mjs fails when the file is out of date.
//
//   node tools/plane-cards.mjs          writes data/plane-cards.json
//   node tools/plane-cards.mjs --check  only says whether it is up to date (exit 1 if not)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { loadContent } from './content.mjs';
import { planeSheet } from '../src/balance/sheet.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const FILE = join(root, 'data/plane-cards.json');

// One plane's card numbers: the seven attributes and the speeds that matter when flying it.
export function cardOf(content, id) {
  const s = planeSheet(content, id);
  const d = content.planeDefs[id];
  return {
    speedLow: s.topSpeed,
    speedHigh: s.topSpeedHigh,
    climb: s.climbRate,
    turn: s.turnTime, // seconds for a full circle: lower is better
    dive: s.diveSpeed,
    firepower: s.firepower,
    toughness: s.hp,
    // Flying hints (world speed units; the hangar shows them in the game's km/h).
    stall: d.stallSpeed,
    tightBelow: d.slowTurnSpeed ?? null, // the tight slow turn works below this
    stiffAbove: d.stiffSpeed ?? null, // the controls stiffen above this
  };
}

export function buildCards(content) {
  const ids = Object.keys(content.planeDefs).filter((id) => content.planeDefs[id]?.name);
  return { _notes: 'Generated by tools/plane-cards.mjs from the plane sheet; do not edit by hand.', planes: Object.fromEntries(ids.map((id) => [id, cardOf(content, id)])) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const cards = buildCards(loadContent());
  const text = JSON.stringify(cards, null, 2) + '\n';
  if (process.argv.includes('--check')) {
    const now = readFileSync(FILE, 'utf8');
    console.log(now === text ? 'data/plane-cards.json is up to date.' : 'data/plane-cards.json is out of date: run node tools/plane-cards.mjs');
    process.exit(now === text ? 0 : 1);
  }
  writeFileSync(FILE, text);
  console.log(`Wrote data/plane-cards.json (${Object.keys(cards.planes).length} planes).`);
}
